def aster_objects(case: dict[str, str]) -> list[str]:
    fiber_spec = (
        f"( plus_end=grow; minus_end=shrink; length={INITIAL_ASTER_LENGTH}; )"
    )
    if case["aster"] == "symmetric":
        return [
            "new 1 nucAster { "
            f"solid=nucCore; type=regular; radius={NUCLEUS_RADIUS}, 0.10; "
            f"fibers={ASTER_FIBERS}, ACTIN, {fiber_spec}; "
            f"position = {fmt_pos(NUCLEUS_START)}; }}"
        ]
    if case["aster"] == "plus_x_cap":
        return [
            "new 1 nucAster { "
            "solid=nucCore; type=angular; direction = 1 0 0; "
            f"aster_angle = {CAP_ANGLE_RAD}; radius={NUCLEUS_RADIUS}, 0.10; "
            f"fibers={ASTER_FIBERS}, ACTIN, {fiber_spec}; "
            f"position = {fmt_pos(NUCLEUS_START)}; }}"
        ]
    raise ValueError(f"unsupported aster mode: {case['aster']}")


def push_objects() -> list[str]:
    return [
        f"new 1 nucBody {{ radius = {NUCLEUS_RADIUS}; position = {fmt_pos(NUCLEUS_START)}; }}",
        "new "
        f"{PUSH_FIBERS} ACTIN {{ "
        f"position = rectangle 0.70 1.80 0.70 at {PUSH_SOURCE_X:.3f} 0 0; "
        "direction = 1 0 0; "
        f"length = {INITIAL_PUSH_LENGTH}; plus_end = grow; minus_end = shrink; "
        "placement = anywhere; "
        "}",
    ]


def external_objects(case: dict[str, str]) -> list[str]:
    ext = case["external"]
    if ext == "none":
        return []
    if ext == "binders":
        return [
            "new 80 fixed_binder { "
            f"position = rectangle 1.10 2.20 0.80 at {MOTOR_PATCH_X:.3f} 0 0; "
            "placement = anywhere; }"
        ]
    if ext == "plus_motors":
        return [
            "new 80 fixed_motor_plus { "
            f"position = rectangle 1.10 2.20 0.80 at {MOTOR_PATCH_X:.3f} 0 0; "
            "placement = anywhere; }"
        ]
    if ext == "minus_motors":
        return [
            "new 80 fixed_motor_minus { "
            f"position = rectangle 1.10 2.20 0.80 at {MOTOR_PATCH_X:.3f} 0 0; "
            "placement = anywhere; }"
        ]
    if ext == "push_binders":
        return [
            "new 80 fixed_binder { "
            f"position = rectangle 0.80 2.20 0.80 at {PUSH_SOURCE_X - 0.20:.3f} 0 0; "
            "placement = anywhere; }"
        ]
    if ext == "push_plus_motors":
        return [
            "new 80 fixed_motor_plus { "
            f"position = rectangle 0.80 2.20 0.80 at {PUSH_SOURCE_X - 0.20:.3f} 0 0; "
            "placement = anywhere; }"
        ]
    raise ValueError(f"unsupported external mode: {ext}")


def config_for(case: dict[str, str], replicate: int, seed: int, *, smoke: bool = False, quick: bool = False) -> str:
    steps, frames = run_length(smoke=smoke, quick=quick)
    lines = [header(case, replicate, seed, smoke=smoke, quick=quick), properties(case), ""]
    if case["mode"] == "aster":
        lines.extend(aster_objects(case))
    elif case["mode"] == "push":
        lines.extend(push_objects())
    else:
        raise ValueError(f"unsupported mode: {case['mode']}")
    lines.extend(external_objects(case))
    lines.append("")
    lines.append(f"run {steps} system {{ nb_frames = {frames} }}")
    return "\n".join(lines) + "\n"


def seed_for(case_index: int, replicate: int) -> int:
    return 91000 + case_index * 100 + replicate


def write_run(case: dict[str, str], case_index: int, replicate: int) -> dict[str, object]:
    seed = seed_for(case_index, replicate)
    run_dir = PRODUCTION / case["name"] / f"r{replicate:04d}"
    run_dir.mkdir(parents=True, exist_ok=True)
    config = run_dir / "config.cym"
    config.write_text(config_for(case, replicate, seed), encoding="utf-8")
    (run_dir / "run.sh").write_text(
        dedent(
            """\
            #!/usr/bin/env bash
            set -euo pipefail
            root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../../../" && pwd)"
            "$root/build_mini_turnover/bin/sim" config.cym
            """
        ),
        encoding="utf-8",
    )
    (run_dir / "run.sh").chmod(0o755)
    return {
        "case": case["name"],
        "description": case["description"],
        "mode": case["mode"],
        "aster": case.get("aster", ""),
        "external": case["external"],
        "replicate": f"r{replicate:04d}",
        "seed": seed,
        "config": str(config.relative_to(ROOT)),
        "duration_s": RUN_STEPS * TIME_STEP,
        "duration_min": RUN_STEPS * TIME_STEP / 60,
        "frames": RUN_FRAMES,
        "nucleus_viscosity": NUCLEUS_VISCOSITY,
        "box_length": " ".join(str(v) for v in BOX_LENGTH),
        "aster_fibers": ASTER_FIBERS if case["mode"] == "aster" else 0,
        "push_fibers": PUSH_FIBERS if case["mode"] == "push" else 0,
        "max_length_um": MAX_LENGTH,
    }


def write_smoke() -> None:
    for idx, case in enumerate(CASES, start=1):
        run_dir = SMOKE / case["name"]
        run_dir.mkdir(parents=True, exist_ok=True)
        (run_dir / "config.cym").write_text(
            config_for(case, 1, seed_for(idx, 1), smoke=True),
            encoding="utf-8",
        )


def write_quick() -> None:
    for idx, case in enumerate(CASES, start=1):
        run_dir = QUICK / case["name"] / "r0001"
        run_dir.mkdir(parents=True, exist_ok=True)
        (run_dir / "config.cym").write_text(
            config_for(case, 1, seed_for(idx, 1), quick=True),
            encoding="utf-8",
        )


def write_manifest(rows: list[dict[str, object]]) -> None:
    with (ROOT / "manifest.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    rows = []
    for case_index, case in enumerate(CASES, start=1):
        for replicate in range(1, REPLICATES + 1):
            rows.append(write_run(case, case_index, replicate))
    write_smoke()
    write_quick()
    write_manifest(rows)
    print(f"Wrote {len(rows)} production configs under {PRODUCTION}")
    print(f"Wrote {len(CASES)} smoke configs under {SMOKE}")
    print(f"Wrote {len(CASES)} quick-look configs under {QUICK}")


if __name__ == "__main__":
    main()
