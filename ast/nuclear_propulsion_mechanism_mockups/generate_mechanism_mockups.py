#!/usr/bin/env python3
"""Generate small nuclear-propulsion mechanism mockups.

The goal is not a production sweep. These configs isolate physical ingredients:
geometry-only asters, fixed external binders, fixed external motors, and
lab-frame polymerization push with and without anchoring.
"""

