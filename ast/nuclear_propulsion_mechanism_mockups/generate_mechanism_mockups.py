def fmt_pos(pos: tuple[float, float, float]) -> str:
    return f"{pos[0]: .3f} {pos[1]: .3f} {pos[2]: .3f}"


def run_length(*, smoke: bool = False, quick: bool = False) -> tuple[int, int]:
    if smoke:
        return SMOKE_STEPS, SMOKE_FRAMES
    if quick:
        return QUICK_STEPS, QUICK_FRAMES
    return RUN_STEPS, RUN_FRAMES


def header(case: dict[str, str], replicate: int, seed: int, *, smoke: bool, quick: bool) -> str:
    steps, frames = run_length(smoke=smoke, quick=quick)
    return dedent(
        f"""\
        % Generated by ast/nuclear_propulsion_mechanism_mockups/generate_mechanism_mockups.py
        % Purpose: minimal mechanism screen for directed nuclear motion.
        % Case: {case["name"]}
        % Replicate: r{replicate:04d}
        % Description: {case["description"]}
        % Duration: {steps * TIME_STEP:.3f} s; frames={frames}

        set simul system
        {{
            random_seed = {seed}
            steric    = 1, 500
            time_step = {TIME_STEP}
            kT        = 0.0042
            viscosity = 0.1
        }}
        set system display {{ back_color=white }}

        set space box {{ shape = rectangle }}
        new box {{ length = {BOX_LENGTH[0]}, {BOX_LENGTH[1]}, {BOX_LENGTH[2]} }}
        """
    )


